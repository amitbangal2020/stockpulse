const BN_DIGITS = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];

/** 2026-09-18 → ১৮ সেপ্টেম্বর, ২০২৬ (no Intl, so the server output is stable). */
export function formatBengaliDate(iso: string): string {
  const [year, month, day] = iso.split("-").map(Number);
  const toBn = (value: number) =>
    String(value)
      .split("")
      .map((digit) => BN_DIGITS[Number(digit)] ?? digit)
      .join("");
  return `${toBn(day)} ${BN_MONTHS[month - 1]}, ${toBn(year)}`;
}

