const HI_DIGITS = ["०", "१", "२", "३", "४", "५", "६", "७", "८", "९"];

/** 2026-09-18 → १८ सितंबर २०२६ (no Intl, so the server output is stable). */
export function formatHindiDate(iso: string): string {
  const [year, month, day] = iso.split("-").map(Number);
  const toHi = (value: number) =>
    String(value)
      .split("")
      .map((digit) => HI_DIGITS[Number(digit)] ?? digit)
      .join("");
  return `${toHi(day)} ${HI_MONTHS[month - 1]} ${toHi(year)}`;
}

